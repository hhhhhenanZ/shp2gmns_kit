"""Step 1 - check region.yaml against your shapefile and OMX files before converting.

Catches the usual problems in seconds instead of partway through a long conversion:
missing files, a field name that does not exist in the shapefile, an OMX file without
the expected matrices.

    python code/check_inputs.py
    python code/check_inputs.py --region path/to/region.yaml
    python code/check_inputs.py --kernel      # also verify TAPlite (TAPlite env only)

Exit code 0 when everything passes, 1 otherwise.
"""

from __future__ import annotations

import argparse
import importlib.util
import sys
from pathlib import Path

CODE_ROOT = Path(__file__).resolve().parent
SOURCE_ROOT = CODE_ROOT / "src"
if str(SOURCE_ROOT) not in sys.path:
    sys.path.insert(0, str(SOURCE_ROOT))

from conic_replay.region import DEFAULT_REGION_FILE, MODES, Region, RegionError  # noqa: E402
from scag_transcad.config import region_is_scag  # noqa: E402
from cmap_emme.config import region_is_cmap  # noqa: E402

CONVERTER = SOURCE_ROOT / "dtalite4cube"
results: list[tuple[str, bool, str]] = []


def check(name: str, ok: bool, detail: str = "") -> bool:
    results.append((name, bool(ok), detail))
    return bool(ok)


def load_constants(path: Path):
    spec = importlib.util.spec_from_file_location(path.stem, path)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def shapefile_fields(path: Path) -> set[str]:
    try:
        import pyogrio
        return {str(name) for name in pyogrio.read_info(str(path))["fields"]}
    except ImportError:
        import geopandas as gpd
        return set(gpd.read_file(str(path), rows=1).columns)


def check_shapefile(region: Region) -> None:
    shp = region.network_shapefile
    if not check("network shapefile exists", shp.is_file(), str(shp)):
        return
    siblings = [shp.with_suffix(ext) for ext in (".dbf", ".shx")]
    check("shapefile .dbf and .shx beside it", all(p.is_file() for p in siblings),
          ", ".join(p.name for p in siblings if not p.is_file()) or "present")
    fields = shapefile_fields(shp)

    names = load_constants(CONVERTER / "cube2gmns" / "fieldnameconfig.py")
    # geometry is read from the shape itself, and the link id is generated by the
    # converter (funclib.py numbers links 1..n before reading), so neither is a field.
    generated = {"geometry_field", "link_id_field"}
    base = [v for k, v in names.cube_base_link_mapping.items() if k not in generated]
    missing = [f for f in base if f not in fields]
    check("converter link fields (fieldnameconfig.py)", not missing,
          f"missing: {missing}" if missing else f"{len(base)} fields found")
    for period in region.periods:
        wanted = [t.format(time_period=period.upper())
                  for t in names.cube_link_dependent_mapping.values()]
        missing = [f for f in wanted if f not in fields]
        check(f"converter {period.upper()} fields (lanes, limit, toll)", not missing,
              f"missing: {missing}" if missing else ", ".join(wanted))

    for period in region.periods:
        wanted = [region.cube_field(k, period) for k in
                  ("volume", "vc_ratio", "travel_time_ratio", "speed", "free_speed", "vmt",
                   "link_capacity", "lane_capacity", "limit")]
        wanted += [region.mode_field(m, period) for m in MODES]
        missing = [f for f in wanted if f not in fields]
        check(f"Cube {period.upper()} results (region.yaml cube_fields)", not missing,
              f"missing: {missing}" if missing else f"{len(wanted)} fields found")
    static = [region.static_field(k) for k in ("street_name", "toll_group", "jurisdiction")]
    missing = [f for f in static if f not in fields]
    check("street name, toll group, jurisdiction fields", not missing,
          f"missing: {missing}" if missing else ", ".join(static))


def check_demand(region: Region) -> None:
    folder = region.demand_folder
    if not check("demand folder exists", folder.is_dir(), str(folder)):
        return
    settings = load_constants(CONVERTER / "settings" / "dtalite_settings_config.py")
    try:
        import openmatrix as omx
    except ImportError:
        check("openmatrix installed", False, "pip install openmatrix")
        return
    files = [p for p in folder.glob("*.omx") if "transit" not in p.name.lower()]
    for period in region.periods:
        matches = [p for p in files if period.upper() in p.stem.upper()]
        if not check(f"{period.upper()} OMX file", bool(matches),
                     ", ".join(p.name for p in matches) or
                     f"no *.omx with '{period.upper()}' in its name in {folder}"):
            continue
        with omx.open_file(str(matches[0]), "r") as matrix:
            present = set(matrix.list_matrices())
            shape = matrix.shape()
        expected = [f"{period.upper()}_{lu.upper()}s" for lu in settings.DEMAND_LANE_USES]
        missing = [m for m in expected if m not in present]
        check(f"{period.upper()} OMX matrices", not missing,
              f"missing: {missing}; found: {sorted(present)}" if missing
              else f"{len(expected)} matrices, {shape[0]} x {shape[1]} zones")


def check_kernel() -> None:
    try:
        from dtalite4cube.taplite_runtime import verify_taplite_runtime
        identity = verify_taplite_runtime()
        check("TAPlite kernel matches code/setup/taplite_pypi_lock.json", True,
              f"{identity['distribution']}=={identity['installed_version']}")
    except Exception as error:  # noqa: BLE001 - report, do not crash
        check("TAPlite kernel matches code/setup/taplite_pypi_lock.json", False, str(error))


def main() -> int:
    if region_is_cmap(sys.argv[1:], DEFAULT_REGION_FILE):
        from cmap_emme.checks import main as check_cmap  # CMAP (Emme): region.cmap.yaml
        return check_cmap(sys.argv[1:])
    if region_is_scag(sys.argv[1:], DEFAULT_REGION_FILE):
        from scag_transcad.checks import main as check_scag
        return check_scag(sys.argv[1:])
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--region", type=Path)
    parser.add_argument("--kernel", action="store_true",
                        help="verify the TAPlite kernel (run inside the TAPlite environment)")
    args = parser.parse_args()

    try:
        region = Region.load(args.region)
        check("region.yaml is complete", True, f"{region.name}: periods {list(region.periods)}")
    except RegionError as error:
        check("region.yaml is complete", False, str(error))
        region = None

    if region is not None:
        check_shapefile(region)
        check_demand(region)
    if args.kernel:
        check_kernel()

    width = max(len(name) for name, _, _ in results)
    print()
    for name, ok, detail in results:
        print(f"  {'PASS' if ok else 'FAIL'}  {name:<{width}}  {detail}")
    failed = sum(1 for _, ok, _ in results if not ok)
    print()
    print(f"  {len(results) - failed} passed, {failed} failed")
    if failed:
        print("  Fix the FAIL lines, then run this again. See README, 'Troubleshooting'.")
    return 1 if failed else 0


if __name__ == "__main__":
    raise SystemExit(main())
